"""Phase 10c paper table (Oct 21, 2026; descriptive). CPU, from results/p10c_summary/summary.json (pre-registered risks)
and results/p10c_explore/explore.json (robust risk under shift, exploratory).

Rows: every pipeline; columns: risk against the reference at dt, dt/2 and dt/4 per set, plus the robust risk under
shift (wrong against all three). The finest reference (dt/4) is the pre-registered primary one.
Output: paper/tab/reference_table.tex (main paper: the rows its text discusses) and paper/supp/reference_table_full.tex
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import results_dir  # noqa: E402

PAPER = Path(__file__).resolve().parents[1] / "paper"
ROWS = [("PhysCtrl", "PhysCtrl"), ("coarse", "Coarse"), ("M1", "Tuned M1"), ("M2", "Tuned M2"), ("M3", "Tuned M3"),
        ("reference (dt)", r"Reference at $\Delta t$"), ("seed spread", "Seed-spread deferral"),
        ("residual gate", "Momentum residual"), ("certify or simulate", "Certify or simulate"), ("ours", "Ours")]
MAIN = {"PhysCtrl", "M1", "M2", "M3", "reference (dt)", "certify or simulate", "ours"}   # Oct 21: page limit
SETS, REFS = ("in distribution", "shift", "contact"), ("dt", "dt/2", "dt/4")


def table(R, G, rows):
    """LaTeX tabular for the given (key, label) rows."""
    tex = [r"% generated by code/p10c_table.py from results/p10c_summary and results/p10c_explore; do not edit by hand",
           r"\begin{tabular}{@{}lcccccccccc@{}}", r"\toprule",
           r" & \multicolumn{3}{c}{In distribution} & \multicolumn{4}{c}{Shift} & \multicolumn{3}{c}{Two-object contact} \\",
           r"\cmidrule(lr){2-4}\cmidrule(lr){5-8}\cmidrule(l){9-11}",
           r"Reference step & $\Delta t$ & $\Delta t/2$ & $\Delta t/4$ & $\Delta t$ & $\Delta t/2$ & $\Delta t/4$ & robust"
           r" & $\Delta t$ & $\Delta t/2$ & $\Delta t/4$ \\", r"\midrule"]
    for k, lab in rows:
        cells = []
        for s in SETS:
            r = R[s].get(k)
            cells += ["--"] * 3 if r is None or r["dt"] is None or r["dt"] != r["dt"] else [f"{r[rn]:.3f}" for rn in REFS]
            if s == "shift":
                cells.append(f"{G[s][k]['robust'][0]:.3f}" if k in G[s] else "--")
        name = r"\textbf{" + lab + "}" if k == "ours" else lab
        if k == "ours":
            tex.append(r"\midrule")
        tex.append(name + " & " + " & ".join(cells) + r" \\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(tex) + "\n"


def main():
    R = json.loads((results_dir("p10c_summary") / "summary.json").read_text())["risk"]
    G = json.loads((results_dir("p10c_explore") / "explore.json").read_text())
    (PAPER / "tab" / "reference_table.tex").write_text(table(R, G, [r for r in ROWS if r[0] in MAIN]))
    (PAPER / "supp" / "reference_table_full.tex").write_text(table(R, G, ROWS))
    print("wrote", PAPER / "tab" / "reference_table.tex", PAPER / "supp" / "reference_table_full.tex")


if __name__ == "__main__":
    main()
