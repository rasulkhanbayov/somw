"""Phase 11 VLM judge (pre-registered Oct 20, 2026; PLAN.md "Phase 11"). GPU (one H200, about an hour).

Qwen2-VL-7B-Instruct (local, greedy). PhysCtrl's own GPT-4o evaluation prompt (its Appendix A), verbatim except that
(i) the force is described in the text instead of a red arrow and (ii) one video is scored per call (input image +
10 evenly spaced frames), so the judge never sees which method produced it. Scores: Semantic Adherence (SA), Physical
Commonsense (PC), Video Quality (VQ), 1-5.
Cases: every case_v2.json under the configured render roots (Phase 11 images and PhysCtrl's 5 examples, job 95);
variants generation (PhysCtrl), certified_v2 (ours) and ground_truth (reference).
Output: results/p11_judge/scores.jsonl (resumable: done (case, variant) pairs are skipped)
  --extract-only (CPU, dev server, before the GPU job): saves the 10 frames of each video as
  <case>/variants/<v>/frames10/NN.png with the system ffmpeg, which the GPU nodes may lack.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import RESULTS_ROOT, append_jsonl, load_config, read_jsonl  # noqa: E402
from fig_deck_video import frame  # noqa: E402

PROMPT = """You are tasked with evaluating the quality of image-to-video generation produced by a model.
For each test case, you will be given:
1. A text prompt describing a single object and a force applied to it.
2. An input image of the object.
3. One set of 10 evenly spaced frames from a video generated by a model from the same input.
Please evaluate this video based on the following three criteria using a 5-point Likert scale (1 = poor, 5 = excellent):
- Semantic Adherence: How well the content and motion in the video match the description in the text prompt, especially the alignment with the force direction and position. Note that the video should starts with the input image.
- Physical Commonsense: Whether the object's motion follows intuitive, physically plausible dynamics given the applied force direction and position.
- Video Quality: The overall visual and temporal quality of the video (note that static or nearly-static sequences are less preferred).
Provide your evaluation for each video strictly in the following one-line format:
Video i, Semantic Adherence score, Physical Commonsense score, Video Quality score

Text prompt: {text}
The first image is the input image; the next 10 images are the video frames in order."""
VARIANTS = ("generation", "certified_v2", "ground_truth")
N_FRAMES_VIDEO = 49


def parse(txt):
    m = re.search(r"Video\s*\d*\s*,\s*([1-5])\s*,\s*([1-5])\s*,\s*([1-5])", txt)
    return tuple(int(x) for x in m.groups()) if m else (None, None, None)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", required=True)
    ap.add_argument("--extract-only", action="store_true")
    args = ap.parse_args()
    cfg = load_config(args.config)
    out = Path(RESULTS_ROOT) / cfg["run_name"]
    out.mkdir(parents=True, exist_ok=True)
    rows = out / "scores.jsonl"
    done = {(r["case"], r["variant"]) for r in read_jsonl(rows)} if rows.exists() else set()
    cases = []
    for root, ex_root in cfg["render_roots"]:
        for c in sorted(Path(os.path.expandvars(root)).glob("*/case_v2.json")):
            rec = json.loads(c.read_text())
            ex = rec.get("example") or rec["case"].split("__")[0]
            cj = json.loads((Path(os.path.expandvars(ex_root)) / ex / "config.json").read_text())
            cases.append((c.parent, rec["case"], cj["prompt"], Path(os.path.expandvars(ex_root)) / ex / "input.png"))
    idx = np.linspace(0, N_FRAMES_VIDEO - 1, 10).round().astype(int)
    from PIL import Image
    if args.extract_only:
        for cdir, case, _, _ in cases:
            for v in VARIANTS:
                mp4, fd = cdir / "variants" / v / "result.mp4", cdir / "variants" / v / "frames10"
                if mp4.exists() and not (fd / "09.png").exists():
                    fd.mkdir(exist_ok=True)
                    for j, k in enumerate(idx):
                        Image.fromarray(frame(mp4, int(k))).save(fd / f"{j:02d}.png")
        print(f"[p11 judge] frames extracted for {len(cases)} cases", flush=True)
        return
    import torch
    from transformers import AutoProcessor, Qwen2VLForConditionalGeneration
    name = cfg["judge_model"]
    model = Qwen2VLForConditionalGeneration.from_pretrained(name, torch_dtype=torch.bfloat16, device_map="cuda")
    proc = AutoProcessor.from_pretrained(name, min_pixels=128 * 28 * 28, max_pixels=320 * 28 * 28)
    for cdir, case, text, inp in cases:
        for v in VARIANTS:
            if (case, v) in done:
                continue
            fd = cdir / "variants" / v / "frames10"
            if not (fd / "09.png").exists():
                append_jsonl({"case": case, "variant": v, "missing": True}, rows)
                continue
            imgs = [Image.open(inp).convert("RGB")] + [Image.open(fd / f"{j:02d}.png").convert("RGB") for j in range(10)]
            msgs = [{"role": "user", "content": [{"type": "image"} for _ in imgs] + [{"type": "text", "text": PROMPT.format(text=text)}]}]
            chat = proc.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
            inputs = proc(text=[chat], images=imgs, return_tensors="pt").to("cuda")
            with torch.no_grad():
                gen = model.generate(**inputs, max_new_tokens=40, do_sample=False)
            txt = proc.batch_decode(gen[:, inputs["input_ids"].shape[1]:], skip_special_tokens=True)[0]
            sa, pc, vq = parse(txt)
            append_jsonl({"case": case, "variant": v, "sa": sa, "pc": pc, "vq": vq, "raw": txt}, rows)
            print(f"[p11 judge] {case} {v}: {sa} {pc} {vq}", flush=True)


if __name__ == "__main__":
    main()
